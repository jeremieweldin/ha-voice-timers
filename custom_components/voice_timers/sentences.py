"""Generate and install the custom-sentences file for Voice Timers.

HA's default conversation agent only reads sentences from the bundled
`home_assistant_intents` package and from
`<config>/custom_sentences/<lang>/*.yaml` — it does NOT scan custom
components, and the old programmatic `async_register_sentence()` was
removed in 2025.10.1. So this integration writes its sentence YAML into
that directory at setup and calls `conversation.reload`, and removes it
again on unload.

The sentence patterns use the same hassil syntax as the original YAML
package's conversation triggers, ported nearly verbatim. `{vt_label:label}`
and `{vt_minutes:minutes}` use namespaced list names (vt_*) so they can't
collide with any built-in list, while still delivering `label`/`minutes`
slots to the intent handlers.
"""
from __future__ import annotations

import logging
import os

import yaml

from homeassistant.core import HomeAssistant

from .const import (
    CONVERSATION_DOMAIN,
    CONVERSATION_RELOAD_SERVICE,
    INTENT_CANCEL_NAMED_TIMER,
    INTENT_SET_NAMED_TIMER,
    INTENT_STOP_RINGING,
    INTENT_TIMER_STATUS,
    LIST_LABEL,
    LIST_MINUTES,
    MINUTES_RANGE_MAX,
    MINUTES_RANGE_MIN,
    SENTENCES_DIR,
    SENTENCES_FILENAME,
    SENTENCES_LANGUAGE,
)

_LOGGER = logging.getLogger(__name__)

_HEADER = (
    "# Auto-generated by the Voice Timers integration — do not edit.\n"
    "# This file is (re)written when the integration is set up or its\n"
    "# options change, and removed when it is uninstalled. Sentence set is\n"
    "# controlled from the integration's options (e.g. the built-in timer\n"
    "# override toggle).\n"
)

# Named-timer patterns (label + minutes). Ported from voice_named_timers.yaml.
_SET_NAMED = [
    f"set a {{{LIST_LABEL}:label}} timer for {{{LIST_MINUTES}:minutes}} minute[s]",
    f"start a {{{LIST_LABEL}:label}} timer for {{{LIST_MINUTES}:minutes}} minute[s]",
    f"set a {{{LIST_MINUTES}:minutes}} minute timer for {{{LIST_LABEL}:label}}",
    f"start a {{{LIST_MINUTES}:minutes}} minute timer for {{{LIST_LABEL}:label}}",
]
# Bare/unnamed patterns — only included when override_builtin_timer is on, so
# "set a timer for 10 minutes" stays inside this system instead of falling
# through to HA core's built-in timer.
_SET_BARE = [
    f"set a timer for {{{LIST_MINUTES}:minutes}} minute[s]",
    f"start a timer for {{{LIST_MINUTES}:minutes}} minute[s]",
]
_CANCEL = [
    f"cancel [the] {{{LIST_LABEL}:label}} timer",
    f"delete [the] {{{LIST_LABEL}:label}} timer",
]
_STATUS = [
    "what timers are (running|going|active)",
    "(list|check) [my] timers",
    "how many timers (are running|do I have|are going)",
    "what timers do I have [running]",
]
_STOP = [
    "stop",
    "stop timer",
    "stop timers",
    "stop the timer",
    "stop the timers",
    "okay stop",
    "ok stop",
    "thank you",
    "thanks",
]


def build_sentences_yaml(override_builtin_timer: bool) -> str:
    """Build the custom-sentences YAML text for the given override setting."""
    set_sentences = list(_SET_NAMED)
    if override_builtin_timer:
        set_sentences += _SET_BARE

    data = {
        "language": SENTENCES_LANGUAGE,
        "intents": {
            INTENT_SET_NAMED_TIMER: {"data": [{"sentences": set_sentences}]},
            INTENT_CANCEL_NAMED_TIMER: {"data": [{"sentences": _CANCEL}]},
            INTENT_TIMER_STATUS: {"data": [{"sentences": _STATUS}]},
            INTENT_STOP_RINGING: {"data": [{"sentences": _STOP}]},
        },
        "lists": {
            LIST_LABEL: {"wildcard": True},
            LIST_MINUTES: {"range": {"from": MINUTES_RANGE_MIN, "to": MINUTES_RANGE_MAX}},
        },
    }
    return _HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)


def _sentences_path(hass: HomeAssistant) -> str:
    return hass.config.path(SENTENCES_DIR, SENTENCES_LANGUAGE, SENTENCES_FILENAME)


def _write_file(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as file:
        file.write(content)


def _remove_file(path: str) -> None:
    try:
        os.remove(path)
    except FileNotFoundError:
        pass


async def async_install_sentences(
    hass: HomeAssistant, override_builtin_timer: bool
) -> None:
    """Write the sentences file and reload the conversation agent."""
    path = _sentences_path(hass)
    content = build_sentences_yaml(override_builtin_timer)
    await hass.async_add_executor_job(_write_file, path, content)
    _LOGGER.debug("Voice Timers: wrote custom sentences to %s", path)
    await _async_reload_conversation(hass)


async def async_remove_sentences(hass: HomeAssistant) -> None:
    """Remove the sentences file and reload the conversation agent."""
    path = _sentences_path(hass)
    await hass.async_add_executor_job(_remove_file, path)
    _LOGGER.debug("Voice Timers: removed custom sentences at %s", path)
    await _async_reload_conversation(hass)


async def _async_reload_conversation(hass: HomeAssistant) -> None:
    if not hass.services.has_service(CONVERSATION_DOMAIN, CONVERSATION_RELOAD_SERVICE):
        _LOGGER.debug(
            "Voice Timers: conversation.reload not available yet; sentences "
            "will load on next restart"
        )
        return
    try:
        await hass.services.async_call(
            CONVERSATION_DOMAIN, CONVERSATION_RELOAD_SERVICE, {}, blocking=True
        )
    except Exception:  # noqa: BLE001 — reload failure shouldn't break setup
        _LOGGER.exception("Voice Timers: conversation.reload failed")
